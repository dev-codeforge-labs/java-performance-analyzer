@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly STORAGE_KEY = 'pa.lang';

  currentLang = signal<Lang>('en');

  readonly langs: Lang[] = ['en', 'es', 'fr', 'de', 'pt', 'it'];
  readonly langLabels = LANG_LABELS;

  constructor() {
    const stored = localStorage.getItem(this.STORAGE_KEY) as Lang;
    if (stored && this.langs.includes(stored)) this.currentLang.set(stored);
  }

  setLang(lang: Lang): void {
    this.currentLang.set(lang);
    localStorage.setItem(this.STORAGE_KEY, lang);
  }

  /** Reactive translation — reads the language signal so templates auto-update on language change */
  t(key: string): string {
    const lang = this.currentLang();
    return T[lang]?.[key] ?? T['en']?.[key] ?? key;
  }
}
